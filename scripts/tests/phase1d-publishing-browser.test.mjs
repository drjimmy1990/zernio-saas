import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { chromium } from 'playwright';
import { build } from 'esbuild';

test('actual publishing React UI: Page selection, media, schedule, partial result and unknown replay', async () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'asra3-publishing-'));
  const entry = `import React from 'react';import {createRoot} from 'react-dom/client';import {ProviderPublishingWorkspace} from '${path.resolve('src/components/dashboard/ProviderPublishingWorkspace.tsx').replaceAll('\\','/')}';createRoot(document.getElementById('root')).render(<ProviderPublishingWorkspace isRTL={new URLSearchParams(location.search).has('rtl')}/>);`;
  const bundled = await build({ stdin: { contents: entry, resolveDir: process.cwd(), loader: 'tsx' }, bundle: true, write: false, format: 'iife', define: { 'process.env.NODE_ENV': '"production"' } });
  fs.writeFileSync(path.join(temp,'fixture.js'), bundled.outputFiles[0].contents);
  const css = fs.readdirSync('.next/static/chunks').filter(file => file.endsWith('.css'))
    .map(file => fs.readFileSync(path.join('.next/static/chunks', file), 'utf8')).join('\n');
  const server = http.createServer((req,res) => { res.setHeader('Content-Type', req.url === '/fixture.js' ? 'application/javascript' : req.url === '/fixture.css' ? 'text/css' : 'text/html');res.end(req.url === '/fixture.js' ? fs.readFileSync(path.join(temp,'fixture.js')) : req.url === '/fixture.css' ? css : '<html><head><meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="/fixture.css"></head><body><div id="root"></div><script src="/fixture.js"></script></body></html>'); });
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  try {
    const page = await browser.newPage();
    const mutations=[];
    let unknown=false;
    let profileId='profile-owned';
    let uploadProvider='zernio-presign';
    const uploads=[];
    let listPosts=[];
    let conflict=false;
    let pageCount=1;
    await page.route('https://upload.example/**', async route => { uploads.push({headers:route.request().headers(),body:route.request().postDataBuffer(),method:route.request().method()});return route.fulfill({status:200,body:''}); });
    await page.route('**/api/publishing**', async route => {
      const req=route.request();
      if(req.method()==='GET' && new URL(req.url()).searchParams.get('action')==='post') return route.fulfill({json:{post:listPosts.find(post=>post._id===new URL(req.url()).searchParams.get('postId')),httpStatus:200}});
      if(req.method()==='GET') return route.fulfill({json: req.url().includes('action=accounts') ? {profileId,accounts:[{_id:'page-owned',platform:'facebook',displayName:'Our Page',isActive:true},{_id:'page-reconnect',platform:'facebook',displayName:'Reconnect Page',needsReconnection:true},{_id:'instagram',platform:'instagram',displayName:'Instagram'}]} : {posts:listPosts,pagination:{page:Number(new URL(req.url()).searchParams.get('page')||1),pages:pageCount,total:listPosts.length}}});
      const body=req.postDataJSON(); mutations.push(body);
      if(body.action==='presign') return route.fulfill({json:{provider:uploadProvider,uploadUrl:'https://upload.example/file',publicUrl:'https://assets.example/upload.jpg',uploadMethod:'PUT',uploadHeaders:uploadProvider==='supabase-white-label-cdn'?{'x-upsert':'false'}:{}}});
      if(body.action==='delete') {listPosts=listPosts.filter(post=>post._id!==body.postId);return route.fulfill({json:{message:'Post deleted',simulated:false,httpStatus:200}});}
      if(conflict)return route.fulfill({status:409,json:{success:false,error:{code:'idempotency_conflict',message:'Intent conflict'}}});
      if(unknown) return route.abort('failed');
      return route.fulfill({status:207,json:{httpStatus:207,post:{_id:'post-real',status:'partial',content:body.content,platforms:[{platform:'facebook',accountId:{_id:'page-owned'},status:'failed',errorMessage:'Permission expired',platformError:{code:'190',message:'Reconnect required'}}]}}});
    });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.getByRole('option',{name:'Our Page',exact:true}).waitFor({state:'attached'});
    assert.equal(await page.getByRole('button',{name:'Save draft',exact:true}).isDisabled(),true);
    assert.equal(await page.getByRole('option',{name:'Reconnect Page — reconnect required'}).getAttribute('disabled'),'');
    assert.equal(await page.getByRole('option',{name:'Instagram · Instagram — inactive',exact:true}).getAttribute('disabled'),'');
    await page.getByLabel('Publishing account').selectOption('page-owned');
    await page.getByLabel('Post text').fill('Hello customers');
    await page.getByText('Add an image or video',{exact:true}).click();
    await page.getByLabel('Upload media',{exact:true}).setInputFiles({name:'first.jpg',mimeType:'image/jpeg',buffer:Buffer.from('first-image')});
    await page.getByText('https://assets.example/upload.jpg',{exact:true}).waitFor();
    assert.equal(uploads[0].method,'PUT');assert.equal(uploads[0].headers['content-type'],'image/jpeg');assert.equal(uploads[0].body.toString(),'first-image');
    await page.getByRole('button',{name:'Remove media',exact:true}).click();
    uploadProvider='supabase-white-label-cdn';
    await page.getByLabel('Upload media',{exact:true}).setInputFiles({name:'second.jpg',mimeType:'image/jpeg',buffer:Buffer.from('second-image')});
    await page.getByText('https://assets.example/upload.jpg',{exact:true}).waitFor();
    assert.equal(uploads[1].headers['x-upsert'],'false');assert.equal(uploads[1].body.toString(),'second-image');
    await page.getByRole('button',{name:'Remove media',exact:true}).click();
    await page.getByText('Add an image or video',{exact:true}).click();
    await page.getByLabel('Media URL',{exact:true}).fill('https://assets.example/image.jpg');
    await page.getByRole('button',{name:'Add',exact:true}).click();
    await page.getByRole('radio',{name:'Schedule',exact:true}).check();
    await page.getByLabel('Schedule date and time').fill('2030-12-01T12:30');
    await page.getByLabel('Timezone',{exact:true}).fill('Africa/Cairo');
    await page.getByRole('button',{name:'Review post',exact:true}).click();
    await page.getByRole('button',{name:'Schedule post',exact:true}).click();
    await page.getByText('Publishing did not fully complete. Review each channel result below.').waitFor();
    const scheduled=mutations.find(m=>m.action==='create');
    assert.equal(scheduled.platforms[0].accountId,'page-owned');
    assert.deepEqual(scheduled.mediaItems,[{type:'image',url:'https://assets.example/image.jpg'}]);
    assert.equal(scheduled.scheduledFor,'2030-12-01T10:30:00.000Z');
    assert.equal(scheduled.timezone,'Africa/Cairo');
    assert.equal(await page.getByRole('link',{name:'View post'}).count(),0);
    await page.getByText('Permission expired',{exact:false}).waitFor();
    unknown=true;
    await page.getByLabel('Post text').fill('Keep this intent');
    await page.getByRole('radio',{name:'Save draft',exact:true}).check();
    await page.getByRole('button',{name:'Save draft',exact:true}).click();
    await page.getByRole('button',{name:'Check with the same request'}).waitFor();
    const prior=mutations.at(-1);
    assert.equal(prior.isDraft,true);
    assert.equal(prior.publishNow,undefined);
    assert.equal(prior.scheduledFor,undefined);
    await page.reload();
    await page.getByRole('button',{name:'Check with the same request'}).click();
    await page.getByRole('alert').waitFor();
    assert.deepEqual(mutations.at(-1),prior);
    conflict=true;unknown=false;
    await page.getByRole('button',{name:'Check with the same request'}).click();
    await page.getByRole('alert').waitFor();
    assert.equal(mutations.at(-1).idempotencyKey,prior.idempotencyKey);
    assert.equal(await page.getByRole('button',{name:'Check with the same request'}).count(),1);
    conflict=false;
    profileId='profile-other';
    await page.reload();
    await page.getByRole('option',{name:'Our Page',exact:true}).waitFor({state:'attached'});
    assert.equal(await page.getByRole('button',{name:'Check with the same request'}).count(),0);
    assert.equal(await page.getByLabel('Post text').inputValue(),'');
    await page.evaluate(()=>sessionStorage.clear());
    profileId='profile-owned';
    listPosts=[{_id:'edit-a',content:'Scheduled review',status:'scheduled',scheduledFor:'2030-12-01T10:30:00.000Z',timezone:'Africa/Cairo',platforms:[{platform:'facebook',accountId:{_id:'page-owned'},status:'pending'}]},
      {_id:'custom-a',content:'Custom review',status:'draft',platforms:[{platform:'facebook',accountId:'page-owned',status:'pending',customContent:'Override'}]},
      {_id:'multi-a',content:'Multi review',status:'draft',platforms:[{platform:'facebook',accountId:'page-owned',status:'pending'},{platform:'facebook',accountId:'other',status:'pending'}]}];
    await page.reload();
    await page.getByText('Scheduled review',{exact:true}).waitFor();
    const scheduledRow=page.locator('article').filter({hasText:'Scheduled review'});
    await scheduledRow.getByRole('button',{name:'Edit',exact:true}).click();
    assert.equal(await page.getByLabel('Publishing account').inputValue(),'page-owned');
    assert.equal(await page.getByLabel('Schedule date and time').inputValue(),'2030-12-01T12:30');
    for(const title of ['Custom review','Multi review'])assert.equal(await page.locator('article').filter({hasText:title}).getByRole('button',{name:'Edit',exact:true}).count(),0);
    unknown=true;
    await page.getByLabel('Post text').fill('Unknown edit');
    await page.getByRole('button',{name:'Review post',exact:true}).click();
    await page.getByRole('button',{name:'Save changes',exact:true}).click();
    await page.getByRole('button',{name:'Review existing post',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Check with the same request'}).count(),0);
    const updateCount=mutations.length;
    await page.getByRole('button',{name:'Review existing post',exact:true}).click();
    assert.equal(mutations.length,updateCount);
    await page.getByRole('button',{name:'I reviewed the result',exact:true}).click();
    listPosts=[{_id:'retry-a',content:'Failed review',status:'failed',platforms:[{platform:'facebook',accountId:'page-owned',status:'failed',errorMessage:'Permission expired'}]}];
    await page.getByRole('button',{name:'Refresh',exact:true}).click();
    await page.getByRole('button',{name:'Retry',exact:true}).click();
    await page.getByRole('button',{name:'Review existing post',exact:true}).waitFor();
    const retryCount=mutations.length;
    await page.getByRole('button',{name:'Review existing post',exact:true}).click();
    assert.equal(mutations.length,retryCount);
    await page.getByRole('button',{name:'I reviewed the result',exact:true}).click();
    unknown=false;
    pageCount=2;
    await page.getByRole('button',{name:'Refresh',exact:true}).click();
    await page.getByRole('button',{name:'Next',exact:true}).click();
    await page.getByText('Page 2',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Remove from workspace',exact:true}).click();
    await page.getByRole('button',{name:'Confirm removal from workspace',exact:true}).click();
    await page.getByText('Post removed from the publishing workspace.',{exact:false}).waitFor();
    assert.equal(listPosts.length,0);
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'scripts/tests/phase1d-publishing-desktop.png',fullPage:true});
    await page.goto(`http://127.0.0.1:${server.address().port}/?rtl`);
    assert.equal(await page.getByTestId('publishing-workspace').getAttribute('dir'),'rtl');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.getByLabel('حساب النشر').isVisible(),true);
    await page.screenshot({path:'scripts/tests/phase1d-publishing-mobile-rtl.png',fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  } finally { await browser.close();await new Promise(resolve=>server.close(resolve)); fs.rmSync(temp,{recursive:true,force:true}); }
});
